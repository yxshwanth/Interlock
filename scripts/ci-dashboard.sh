#!/usr/bin/env bash
# Last 30 completed CI runs: pass rate, p50/p90 wall time (ROADMAP §29, §80).
#   scripts/ci-dashboard.sh > docs/ci_dashboard.md
set -euo pipefail
gh run list --workflow CI --status completed --limit 30 \
	--json databaseId,conclusion,createdAt,updatedAt,event,headBranch |
python3 -c '
import json, sys
from datetime import datetime
def t(s): return datetime.fromisoformat(s.replace("Z", "+00:00"))
runs = json.load(sys.stdin)
for r in runs: r["sec"] = (t(r["updatedAt"]) - t(r["createdAt"])).total_seconds()
secs = sorted(r["sec"] for r in runs)
def pct(p): return secs[min(len(secs) - 1, int(p * len(secs)))]
ok = sum(r["conclusion"] == "success" for r in runs)
print("# CI dashboard (last %d completed CI runs)\n" % len(runs))
print("Generated by `scripts/ci-dashboard.sh`. Wall time is created-to-updated, so it includes queueing.\n")
print("- pass rate: %d/%d" % (ok, len(runs)))
print("- p50: %.0f s, p90: %.0f s (PR-tier budget: 900 s)\n" % (pct(0.5), pct(0.9)))
print("| run | event | branch | result | seconds |\n|---|---|---|---|---|")
for r in runs: print("| %d | %s | %s | %s | %.0f |" % (r["databaseId"], r["event"], r["headBranch"], r["conclusion"], r["sec"]))
'
